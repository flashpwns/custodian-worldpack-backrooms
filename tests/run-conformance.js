"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { validateWorldPackConformance, createSession, advanceSession, exportSession, restoreSession } = require("custodian");
const root = path.resolve(__dirname, "..");
const world_pack = JSON.parse(fs.readFileSync(path.join(root, "manifest.json"), "utf8"));
const scenario = JSON.parse(fs.readFileSync(path.join(root, "scenario.json"), "utf8"));
const initial = createSession({ world_pack, scenario });
assert.equal(initial.ok, true, JSON.stringify(initial.error));
const visual = (observer) => ({ request: { id: `${observer}-controlled-light`, observer, projection_identity: initial.session.projection.identity, modality: "visual", target: "controlled-light" }, context: { observer, location: "complex-side-controlled-area", capabilities: ["visual"] } });
const traversal = advanceSession({ session: initial.session, tick: { id: "threshold-entry", at: 1, observers: [{ id: "async-surveyor-alpha", goals: [{ id: "enter-controlled-area", intent: "traverse-controlled-route", priority: 1 }], plans: [], perception: visual("async-surveyor-alpha") }, { id: "async-surveyor-beta", goals: [], plans: [], perception: visual("async-surveyor-beta") }] } });
assert.equal(traversal.ok, true, JSON.stringify(traversal.error));
assert.equal(traversal.tick_result.state.local.perceptions["async-surveyor-alpha"].length, 1);
assert.equal(traversal.tick_result.state.local.perceptions["async-surveyor-beta"].length, 1);
assert.equal(traversal.session.projection.objective.environment.positions["async-surveyor-alpha"], "complex-side-controlled-area");
assert.equal(traversal.session.projection.objective.messages.length, 1);
const measurement = advanceSession({ session: traversal.session, tick: { id: "threshold-measurement", at: 2, observers: [{ id: "async-surveyor-alpha", goals: [{ id: "record-baseline", intent: "toggle-light", priority: 1 }], plans: [] }, { id: "async-surveyor-beta", goals: [], plans: [] }] } });
assert.equal(measurement.ok, true, JSON.stringify(measurement.error));
assert.equal(measurement.session.projection.objective.evidence.length, 1);
const restored = restoreSession(exportSession(measurement.session).envelope);
assert.equal(restored.ok, true, JSON.stringify(restored.error));
const report = validateWorldPackConformance({ world_pack, scenarios: [{ scenario, ticks: [] }] });
assert.equal(report.ok, true);
process.stdout.write(`${report.serialization}\n`);
